import unreal as u
bp = u.load_asset('/Game/Prototype/BP_Fighter')
ed = u.BlueprintGraphEditor.get_graph_editor_by_name(bp, 'ResolveStrike')
entry = ed.find_graph_entry_pin()
targets = entry.list_connected_pins()
assert len(targets) == 1
entry.break_pin_links()
pending = ed.add_get_member_variable_node('AttackPending')
branch = ed.add_branch_node()
assert entry.try_create_connection(branch.find_execute_pin())
assert pending.find_output_pin('AttackPending').try_create_connection(branch.find_condition_pin())
windup = ed.add_get_member_variable_node('Windup')
due = ed.add_call_function_node('/Script/Engine.KismetMathLibrary.LessEqual_DoubleDouble')
assert windup.find_output_pin('Windup').try_create_connection(due.find_input_pin('A'))
assert due.find_input_pin('B').set_pin_value('0')
branch_due = ed.add_branch_node()
assert branch.find_then_pin().try_create_connection(branch_due.find_execute_pin())
assert due.find_result_pin().try_create_connection(branch_due.find_condition_pin())
assert branch_due.find_then_pin().try_create_connection(targets[0])
assert u.BlueprintEditorLibrary.compile_blueprint(bp)
assert u.EditorAssetLibrary.save_loaded_asset(bp)
u.log('STRIKE_GUARD_PATCH_PASSED')
